#!/usr/bin/env node
// Generates skills/api/reference/*.md, the API skill's endpoint reference,
// from Taxbit's OpenAPI specs.
//
//   node scripts/generate-api-reference.mjs                   fetch the specs from GitHub (needs `gh` access to taxbit-private/readme-apidocs)
//   node scripts/generate-api-reference.mjs --spec-dir DIR    read api.json and embedded-api.json from DIR
//   node scripts/generate-api-reference.mjs --check           fail if the committed reference is out of date
//
// Output: reference/<area>.md per spec tag (the area's notes from
// src/api-notes/<area>.md, then an endpoint index), reference/<area>/<endpoint>.md
// per operation, and reference/values/<list>.md per long allowed-value list.
// Never edit skills/api/reference/ by hand.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { FIELD_NOTES } from '../src/field-notes.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'skills', 'api', 'reference');
const NOTES_DIR = join(ROOT, 'src', 'api-notes');

export const SPEC_SOURCE = {
  repo: 'taxbit-private/readme-apidocs',
  ref: 'v1.0.0',
  files: { api: 'reference/api.json', embedded: 'reference/embedded-api.json' },
};

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
// Enums longer than this get their own file under reference/values/.
const INLINE_ENUM_LIMIT = 20;
const MAX_DEPTH = 5;

export function slug(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

// Paths without the /v1 prefix: the skill's base URLs already end in /v1.
export function displayPath(path) {
  return path.replace(/^\/v1(?=\/)/, '');
}

function resolver(spec) {
  const schemas = spec.components?.schemas ?? {};
  return (node) => {
    let current = node;
    const seen = [];
    while (current?.$ref) {
      const name = current.$ref.split('/').pop();
      if (seen.includes(name)) return { description: `(recursive: ${name})` };
      seen.push(name);
      current = { ...schemas[name], 'x-name': current['x-name'] ?? name };
    }
    return current ?? {};
  };
}

function oneLine(text = '') {
  return String(text).replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|').trim();
}

function sentence(text = '') {
  const trimmed = oneLine(text);
  return !trimmed || /[.!?:)]$/.test(trimmed) ? trimmed : `${trimmed}.`;
}

function code(value) {
  return `\`${String(value).replace(/`/g, "'")}\``;
}

function typeLabel(schema, resolveRef) {
  if (schema.type === 'array') {
    const items = resolveRef(schema.items ?? {});
    return `array of ${items.type ?? (items.properties ? 'object' : 'value')}`;
  }
  if (schema.oneOf || schema.anyOf) return 'one of several shapes';
  const type = schema.type ?? (schema.properties ? 'object' : 'value');
  return schema.format ? `${type} (${schema.format})` : type;
}

// Collects long enums so each is written once, to its own file.
class ValueLists {
  constructor() {
    this.lists = new Map();
  }

  describe(values, name) {
    if (values.length <= INLINE_ENUM_LIMIT) return `One of: ${values.map(code).join(', ')}.`;
    const key = JSON.stringify(values);
    if (!this.lists.has(key)) {
      const base = name.replace(/\[\]/g, '').split('.').pop();
      let label = base;
      let n = 2;
      while ([...this.lists.values()].some((l) => l.label === label)) label = `${base}-${n++}`;
      this.lists.set(key, { label, values });
    }
    const { label } = this.lists.get(key);
    return `One of ${values.length} values: see [values/${slug(label)}.md](../values/${slug(label)}.md).`;
  }

  // One small file per long list, so an agent opens only the list it needs.
  render() {
    return Object.fromEntries([...this.lists.values()].map(({ label, values }) => [
      `values/${slug(label)}.md`,
      `${GENERATED_NOTE('values')}\n\n# ${label}\n\n${values.length} allowed values:\n\n${values.map(code).join(', ')}\n`,
    ]));
  }
}

const GENERATED_NOTE = (file) =>
  `<!-- Generated by scripts/generate-api-reference.mjs from the Taxbit OpenAPI spec. Do not edit${file === 'values' ? '' : `; area notes come from src/api-notes/${file}`}. -->`;

// Rows of a field table: every property, nested ones as `parent.child` and
// array items as `parent[].child`.
export function fieldRows(schema, resolveRef, valueLists, prefix = '', required = [], depth = 0) {
  const node = resolveRef(schema);
  const rows = [];
  for (const [name, raw] of Object.entries(node.properties ?? {})) {
    const property = resolveRef(raw);
    const path = prefix ? `${prefix}.${name}` : name;
    const parts = [];
    if (property.description) parts.push(sentence(property.description));
    const values = property.enum ?? (property.type === 'array' ? resolveRef(property.items ?? {}).enum : undefined);
    if (values) parts.push(valueLists.describe(values, path));
    if (property.deprecated || raw.deprecated) parts.push('**Deprecated.**');
    if (property.nullable) parts.push('Nullable.');
    if (FIELD_NOTES[name]) parts.push(`**Note:** ${FIELD_NOTES[name]}`);
    rows.push({ path, type: typeLabel(property, resolveRef), required: required.includes(name), description: parts.join(' ') });

    if (depth >= MAX_DEPTH) continue;
    if (property.type === 'array') {
      const items = resolveRef(property.items ?? {});
      if (items.properties) rows.push(...fieldRows(items, resolveRef, valueLists, `${path}[]`, items.required ?? [], depth + 1));
    } else if (property.properties) {
      rows.push(...fieldRows(property, resolveRef, valueLists, path, property.required ?? [], depth + 1));
    }
  }
  return rows;
}

function fieldTable(rows) {
  if (!rows.length) return '';
  const lines = ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |'];
  for (const row of rows) lines.push(`| ${code(row.path)} | ${row.type} | ${row.required ? 'Yes' : 'No'} | ${row.description} |`);
  return lines.join('\n');
}

// Tables for a body or response schema; `oneOf` shapes get one table each.
function schemaTables(schema, resolveRef, valueLists) {
  const node = resolveRef(schema);
  const variants = node.oneOf ?? node.anyOf;
  if (variants) {
    return variants.map((variant, i) => {
      const v = resolveRef(variant);
      const title = oneLine(v.title ?? v['x-name'] ?? `Shape ${i + 1}`);
      const about = v.description ? `\n\n${sentence(v.description)}` : '';
      return `**Shape ${i + 1}: ${title}**${about}\n\n${fieldTable(fieldRows(v, resolveRef, valueLists, '', v.required ?? []))}`;
    }).join('\n\n');
  }
  if (node.type === 'array') {
    const items = resolveRef(node.items ?? {});
    return `An array of objects with these fields:\n\n${fieldTable(fieldRows(items, resolveRef, valueLists, '[]', items.required ?? []))}`;
  }
  return fieldTable(fieldRows(node, resolveRef, valueLists, '', node.required ?? []));
}

function paramTable(params, resolveRef, valueLists, withType) {
  const lines = withType
    ? ['| Name | Type | Required | Description |', '| --- | --- | --- | --- |']
    : ['| Name | Description |', '| --- | --- |'];
  for (const param of params) {
    const schema = resolveRef(param.schema ?? {});
    const parts = [sentence(param.description)];
    const values = schema.enum ?? (schema.type === 'array' ? resolveRef(schema.items ?? {}).enum : undefined);
    if (values) parts.push(valueLists.describe(values, param.name));
    const description = parts.filter(Boolean).join(' ');
    lines.push(withType
      ? `| ${code(param.name)} | ${typeLabel(schema, resolveRef)} | ${param.required ? 'Yes' : 'No'} | ${description} |`
      : `| ${code(param.name)} | ${description} |`);
  }
  return lines.join('\n');
}

function exampleOf(content, resolveRef) {
  if (content.example !== undefined) return content.example;
  const first = Object.values(content.examples ?? {})[0];
  if (first?.value !== undefined) return first.value;
  return resolveRef(content.schema ?? {}).example;
}

function jsonBlock(value) {
  return `\`\`\`json\n${JSON.stringify(value)}\n\`\`\``;
}

const SHORT_TOKEN = { tenant: 'tenant', 'account-owner': 'account owner', none: 'none' };

const TOKEN_LABELS = { tenant: 'tenant-scoped token', 'account-owner': 'account-owner-scoped token', none: 'no token' };

function tokenOf(op, source) {
  if (op.security?.every((requirement) => Object.keys(requirement).length === 0)) return 'none';
  return source === 'embedded' ? 'account-owner' : 'tenant';
}

export function renderOperation({ path, method, op, source }, resolveRef, valueLists, seenResponses = new Map()) {
  const title = oneLine(op.summary || op.operationId);
  const out = [`## ${title}`, '', `${code(`${method.toUpperCase()} ${displayPath(path)}`)} · ${TOKEN_LABELS[tokenOf(op, source)]}`];
  if (op.deprecated) out.push('', '**Deprecated.**');
  if (op.description && oneLine(op.description).replace(/\.$/, '').toLowerCase() !== title.replace(/\.$/, '').toLowerCase()) {
    out.push('', op.description.trim());
  }

  const params = (op.parameters ?? []).filter((p) => !(p.in === 'header' && p.name.toLowerCase() === 'content-type'));
  const byIn = (where) => params.filter((p) => p.in === where);
  if (byIn('path').length) out.push('', '**Path parameters**', '', paramTable(byIn('path'), resolveRef, valueLists, false));
  if (byIn('query').length) out.push('', '**Query parameters**', '', paramTable(byIn('query'), resolveRef, valueLists, true));
  if (byIn('header').length) out.push('', '**Headers**', '', paramTable(byIn('header'), resolveRef, valueLists, true));

  const body = op.requestBody?.content?.['application/json'];
  if (body) {
    out.push('', `**Request body** (${op.requestBody.required ? 'required' : 'optional'}, JSON)`, '', schemaTables(body.schema, resolveRef, valueLists));
    const example = exampleOf(body, resolveRef);
    if (example !== undefined) out.push('', 'Example request body:', '', jsonBlock(example));
  }

  const responses = Object.entries(op.responses ?? {});
  const success = responses.filter(([status]) => status.startsWith('2'));
  const bodyRows = body?.schema ? new Set(fieldRows(body.schema, resolveRef, new ValueLists()).map((r) => r.path)) : new Set();
  for (const [status, response] of success) {
    out.push('', `**Response ${status}**${response.description ? `: ${oneLine(response.description)}` : ''}`);
    const content = response.content?.['application/json'];
    if (!content?.schema) continue;
    const key = JSON.stringify(resolveRef(content.schema));
    const node = resolveRef(content.schema);
    const rows = node.oneOf || node.anyOf || node.type === 'array' ? null : fieldRows(node, resolveRef, valueLists, '', node.required ?? []);
    const wrapped = rows && bodyRows.size && rows.filter((r) => bodyRows.has(r.path.replace(/^data\./, ''))).length >= bodyRows.size * 0.8;
    // Order matters: "returns the body" beats "same as another endpoint",
    // which beats a full table.
    if (wrapped) {
      const added = rows.filter((r) => !bodyRows.has(r.path.replace(/^data\./, '')));
      const prefix = rows.some((r) => r.path.startsWith('data.')) ? 'Returns the submitted body under `data`' : 'Returns the submitted body';
      out.push('', added.length ? `${prefix}, plus:\n\n${fieldTable(added)}` : `${prefix}.`);
      continue;
    }
    if (seenResponses.has(key)) {
      out.push('', `Same fields as the response of [${seenResponses.get(key).title}](${seenResponses.get(key).file}).`);
      continue;
    }
    const tables = schemaTables(content.schema, resolveRef, valueLists);
    if (tables) out.push('', tables);
    if (op._file) seenResponses.set(key, { title: oneLine(op.summary || op.operationId), file: op._file });
  }
  const errors = responses.filter(([status]) => !status.startsWith('2'));
  if (errors.length) {
    out.push('', `**Errors:** ${errors.map(([status, r]) => `${status}${r.description ? ` ${oneLine(r.description)}` : ''}`).join(' · ')}`);
  }
  return out.join('\n');
}

// A file name for an operation: its summary, falling back to the operationId,
// made unique within the area.
function operationFile(op, source, taken) {
  let base = slug(op.summary || op.operationId.split('_').pop());
  if (source === 'embedded') base = `${base}-owner-token`;
  let name = base;
  for (let n = 2; taken.has(name); n++) name = `${base}-${n}`;
  taken.add(name);
  return `${name}.md`;
}

// Groups every operation by spec tag. Each area gets <area>.md (notes plus an
// index) and <area>/<operation>.md per endpoint; long enums go to value-lists.md.
export function buildReference({ api, embedded }, notes = {}) {
  const groups = new Map();
  for (const [source, spec] of [['api', api], ['embedded', embedded]]) {
    const resolveRef = resolver(spec);
    for (const [path, item] of Object.entries(spec.paths ?? {})) {
      for (const method of METHODS) {
        const op = item[method];
        if (!op) continue;
        const tag = op.tags?.[0];
        if (!tag) throw new Error(`${method.toUpperCase()} ${path} has no tag`);
        const area = slug(tag);
        if (!groups.has(area)) groups.set(area, { tag, ops: [] });
        groups.get(area).ops.push({ path, method, op, source, resolveRef });
      }
    }
  }

  const valueLists = new ValueLists();
  const files = {};
  const areas = [];
  for (const [area, { tag, ops }] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const taken = new Set();
    const index = [];
    const seenResponses = new Map();
    for (const o of ops) {
      const file = `${area}/${operationFile(o.op, o.source, taken)}`;
      o.op._file = file.split('/')[1];
      files[file] = [
        GENERATED_NOTE(`${area}.md`),
        '',
        `# ${tag}: ${oneLine(o.op.summary || o.op.operationId)}`,
        '',
        `Area overview and notes: [${area}.md](../${area}.md)`,
        '',
        renderOperation(o, o.resolveRef, valueLists, seenResponses).replace(/^## .*\n\n/, ''),
      ].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
      index.push(`| [${o.method.toUpperCase()} ${displayPath(o.path)}](${file}) | ${oneLine(o.op.summary || o.op.operationId)} | ${SHORT_TOKEN[tokenOf(o.op, o.source)]} |`);
    }
    const note = notes[`${area}.md`] ? `## Notes\n\n${notes[`${area}.md`].trim()}\n\n` : '';
    files[`${area}.md`] = [
      GENERATED_NOTE(`${area}.md`),
      '',
      `# ${tag}`,
      '',
      note + '## Endpoints',
      '',
      'Open an endpoint\'s file for its parameters, body fields, allowed values, example, and responses.',
      '',
      '| Endpoint | Summary | Token |',
      '| --- | --- | --- |',
      ...index,
    ].join('\n').trimEnd() + '\n';
    areas.push({ area, tag, count: ops.length });
  }
  Object.assign(files, valueLists.render());
  return { files, areas, count: areas.reduce((n, a) => n + a.count, 0) };
}

function readNotes() {
  if (!existsSync(NOTES_DIR)) return {};
  return Object.fromEntries(readdirSync(NOTES_DIR).filter((f) => f.endsWith('.md')).map((f) => [f, readFileSync(join(NOTES_DIR, f), 'utf8')]));
}

function gh(args) {
  return execFileSync('gh', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function fetchSpecs() {
  const { repo, ref, files } = SPEC_SOURCE;
  const sha = gh(['api', `repos/${repo}/commits/${ref}`, '--jq', '.sha']).trim();
  const read = (file) => JSON.parse(gh(['api', '-H', 'Accept: application/vnd.github.raw', `repos/${repo}/contents/${file}?ref=${sha}`]));
  return { sha, api: read(files.api), embedded: read(files.embedded) };
}

function main(argv) {
  const option = (name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
  const specDir = option('--spec-dir');
  const specs = specDir
    ? { sha: 'local', api: JSON.parse(readFileSync(join(specDir, 'api.json'), 'utf8')), embedded: JSON.parse(readFileSync(join(specDir, 'embedded-api.json'), 'utf8')) }
    : fetchSpecs();

  const notes = readNotes();
  const { files, count } = buildReference(specs, notes);
  const unused = Object.keys(notes).filter((file) => !files[file]);
  if (unused.length) throw new Error(`src/api-notes has notes for areas no longer in the spec: ${unused.join(', ')}`);

  if (argv.includes('--check')) {
    const stale = Object.keys(files).filter((file) => !existsSync(join(OUT_DIR, file)) || readFileSync(join(OUT_DIR, file), 'utf8') !== files[file]);
    const extra = existsSync(OUT_DIR) ? readdirSync(OUT_DIR, { recursive: true }).filter((file) => file.endsWith('.md') && !files[file]) : [];
    if (stale.length || extra.length) {
      console.error(`skills/api/reference is out of date: ${[...stale, ...extra].join(', ')}. Run node scripts/generate-api-reference.mjs.`);
      process.exit(1);
    }
    console.error('skills/api/reference is up to date.');
    return;
  }

  rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(dirname(join(OUT_DIR, file)), { recursive: true });
    writeFileSync(join(OUT_DIR, file), text);
  }
  const kb = Math.round(Object.values(files).reduce((n, t) => n + t.length, 0) / 1024);
  const largest = Object.entries(files).sort(([, a], [, b]) => b.length - a.length)[0];
  console.error(`Wrote ${count} operations to ${Object.keys(files).length} files in skills/api/reference (${kb} KB total, largest ${largest[0]} ${Math.round(largest[1].length / 1024)} KB, spec ${specs.sha.slice(0, 12)}).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main(process.argv.slice(2));
  } catch (err) {
    console.error(`generate: ${err.message}`);
    process.exit(1);
  }
}
